export function createAdminSectionProxy(name) {
  const computed = Object.fromEntries(
    ADMIN_SECTION_PROXY_KEYS.map(key => [
      key,
      {
        get() {
          const value = this.adminDashboard[key];
          return typeof value === 'function' ? value.bind(this.adminDashboard) : value;
        },
        set(value) {
          this.adminDashboard[key] = value;
        }
      }
    ])
  );

  return {
    name,
    inject: ['adminDashboard'],
    computed
  };
}
